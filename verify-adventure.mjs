assert.equal(run("restored({...BASE,schema:2,stars:26,equipped:{head:1,back:3},claimed:[0,1,2,3]}).equipped.look"),1,'Existing rewards migrate to earned full costumes');
assert.equal(run("Guide.score({name:'Microsoft Helena',lang:'es-ES',voiceURI:'helena'})>Guide.score({name:'Google español',lang:'es-ES',voiceURI:'google'})"),true);
assert.equal(run("Guide.score({name:'Paulina',lang:'es-MX',voiceURI:'paulina'})>Guide.score({name:'Microsoft Pablo',lang:'es-ES',voiceURI:'pablo'})"),true,'Feminine voice takes priority over locale');
assert.equal(run("Guide.narration('Vamos juntas')"),'Vamos en equipo','Fallback narration uses neutral grammar');
run("save()");assert.equal(run("restored(JSON.parse(localStorage.getItem(SAVE_KEY))).character"),'mira');
