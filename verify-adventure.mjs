const files=[...html.matchAll(/<script src="([^"]+)"/g)].map(m=>m[1].split('?')[0]);
for(const f of files)vm.runInContext(fs.readFileSync(WEB+''+f,'utf8'),sandbox,{filename:f});
const run=s=>vm.runInContext(s,sandbox);
