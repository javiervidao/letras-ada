import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const WEB=fs.existsSync('dist/index.html')?'dist/':'';
const html=fs.readFileSync(WEB+'index.html','utf8');
const nodes=new Map();
